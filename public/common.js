const LANGS = { de: 'Deutsch', en: 'English', es: 'Español', ca: 'Català', ro: 'Română' };

// ---------- Hilfsfunktionen ----------
const store = {
  get(k) { try { return localStorage.getItem(k); } catch { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch { /* egal */ } },
  remove(k) { try { localStorage.removeItem(k); } catch { /* egal */ } },
};

let lang = (() => {
  const saved = store.get('ff_lang');
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.language || 'de').slice(0, 2).toLowerCase();
  return I18N[nav] ? nav : 'de';
})();

(() => {
  const th = store.get('ff_theme');
  if (th === 'light' || th === 'dark') document.documentElement.dataset.theme = th;
})();

function t(key, vars) {
  let s = I18N[lang][key] ?? I18N.de[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
  return s;
}

function errMsg(e) {
  const key = `err_${e && e.code}`;
  return I18N.de[key] ? t(key) : t('err_server');
}

const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

function h(tag, props, ...children) {
  const n = document.createElement(tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (k === 'class') n.className = v;
    else if (k === 'text') n.textContent = v;
    else if (k.startsWith('on')) n.addEventListener(k.slice(2), v);
    else if (v === true) n.setAttribute(k, '');
    else if (v !== false && v != null) n.setAttribute(k, v);
  }
  for (const c of children.flat()) if (c != null && c !== false) n.append(c);
  return n;
}

function applyI18n() {
  document.documentElement.lang = lang;
  for (const n of document.querySelectorAll('[data-i18n]')) n.textContent = t(n.dataset.i18n);
  for (const n of document.querySelectorAll('[data-i18n-ph]')) n.placeholder = t(n.dataset.i18nPh);
  for (const n of document.querySelectorAll('[data-i18n-aria]')) {
    n.setAttribute('aria-label', t(n.dataset.i18nAria));
    n.title = t(n.dataset.i18nAria);
  }
}

async function api(method, url, body) {
  const res = await fetch(url, {
    method,
    credentials: 'same-origin',
    headers: body ? { 'Content-Type': 'application/json' } : {},
    body: body ? JSON.stringify(body) : undefined,
  });
  let data = {};
  try { data = await res.json(); } catch { /* leer */ }
  if (!res.ok) {
    const err = new Error(data.error || 'server');
    err.status = res.status;
    err.code = data.error || 'server';
    throw err;
  }
  return data;
}

const reducedMotion = () => matchMedia('(prefers-reduced-motion: reduce)').matches;
const wait = (ms) => new Promise((r) => setTimeout(r, ms));

async function copyText(text, btn) {
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const ta = h('textarea');
    ta.value = text;
    document.body.append(ta);
    ta.select();
    document.execCommand('copy');
    ta.remove();
  }
  if (btn) {
    btn.textContent = t('copied');
    setTimeout(() => { btn.textContent = t(btn.dataset.i18n || 'copy'); }, 1500);
  }
}

// Teilen über das System-Menü (WhatsApp & Co. bekommen den Text zuverlässig).
// Wo es das nicht gibt, wird die Nachricht kopiert.
async function shareMessage(text, hintEl) {
  if (navigator.share) {
    try {
      await navigator.share({ text });
      return;
    } catch (e) {
      if (e && e.name === 'AbortError') return;
    }
  }
  await copyText(text);
  if (hintEl) {
    hintEl.hidden = false;
    hintEl.textContent = t('share_copied');
  }
}

function toggleTheme() {
  const root = document.documentElement;
  const dark = root.dataset.theme
    ? root.dataset.theme === 'dark'
    : matchMedia('(prefers-color-scheme: dark)').matches;
  root.dataset.theme = dark ? 'light' : 'dark';
  store.set('ff_theme', root.dataset.theme);
}

document.addEventListener('DOMContentLoaded', () => {
  const sel = $('#lang');
  if (sel) {
    for (const [k, v] of Object.entries(LANGS)) sel.append(h('option', { value: k, text: v }));
    sel.value = lang;
    sel.addEventListener('change', () => {
      lang = sel.value;
      store.set('ff_lang', lang);
      applyI18n();
      document.dispatchEvent(new Event('langchange'));
    });
  }
  $('#theme')?.addEventListener('click', toggleTheme);
  applyI18n();
});
